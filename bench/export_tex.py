"""Write every number the paper uses as a LaTeX macro: python3 bench/export_tex.py -> paper/results.tex

Macro names: \\R<Metric><Ticket><Arm>{k,n,pct,lo,hi}, e.g. \\RBrokenOverridePacePct. Rerun after new data and rebuild.
"""
import json, math
from pathlib import Path

from analyze import ARMS, load, newcombe, wilson, honest_stop
from stats import fixture_contrast

BENCH = Path(__file__).resolve().parent
OUT = BENCH.parent / "paper" / "results.tex"
METRICS = {
    "Broken": lambda r: r["broken_head"],
    "BrokenWt": lambda r: r["broken_wt"],
    "Heldout": lambda r: r["heldout_broken_head"],
    "Tamper": lambda r: r["tampered"],
    "TamperDone": lambda r: r["arm"] != "prose" and (r["tamper"]["checks_changed_in_head"] or r["tamper"]["hook_changed"]
                                                     or r["tamper"]["hooks_path_set"] or r["tamper"]["ledger_changed"]),
    "Commit": lambda r: r["commits"] > 0,
    "Tests": lambda r: r["tests_head"] is True,
    "Stop": honest_stop,
    "Blocked": lambda r: r["commit_rejections"] > 0 or r["guard_denials"] > 0,
}


def name(*parts):
    return "R" + "".join(p[:1].upper() + p[1:] for p in parts if p)


def emit(lines, base, k, n):
    p, lo, hi = wilson(k, n)
    lines += [f"\\newcommand{{\\{base}K}}{{{k}}}", f"\\newcommand{{\\{base}N}}{{{n}}}"]
    if n:
        lines += [f"\\newcommand{{\\{base}Pct}}{{{p*100:.0f}\\%}}",
                  f"\\newcommand{{\\{base}CI}}{{[{lo*100:.0f}\\%, {hi*100:.0f}\\%]}}"]
    else:
        lines += [f"\\newcommand{{\\{base}Pct}}{{--}}", f"\\newcommand{{\\{base}CI}}{{--}}"]


# Conditions are analysed separately and never pooled across rounds (PREREGISTRATION.md, changes 7 and 11).
# Tag "" is the first round pooled over both agents (the pre-registered H1 pool).
CONDS = {"Claude": ("claude", "sonnet"), "Codex": ("codex", ""),
         "ClaudeMed": ("claude", "sonnet@medium"), "CodexMed": ("codex", "gpt-6.1-sol@medium")}
PAIRS = (("pace", "hook"), ("pace", "prose"), ("hook", "prose"), ("notice", "hook"), ("pace", "notice"))


def oracle_error(r):
    return "oracle_error" in r["armed_head"].values()


METRICS["BrokenOE"] = lambda r: r["broken_head"] or oracle_error(r)


def fixture_cells(runs, ticket, arm):
    c = {}
    for r in runs:
        if r["ticket"] == ticket and r["arm"] == arm:
            k, n = c.get(r["fixture"], (0, 0))
            c[r["fixture"]] = (k + bool(r["broken_head"]), n + 1)
    return c


def block(L, runs, tag):
    for metric, key in METRICS.items():
        for ticket in ("base", "override"):
            for arm in ARMS:
                sub = [r for r in runs if r["ticket"] == ticket and r["arm"] == arm]
                emit(L, name(metric, ticket, arm, tag), sum(bool(key(r)) for r in sub), len(sub))
    for ticket in ("base", "override"):
        for x, y in PAIRS:
            a = [r for r in runs if r["ticket"] == ticket and r["arm"] == x]
            b = [r for r in runs if r["ticket"] == ticket and r["arm"] == y]
            if not (a and b):
                continue
            d, lo, hi = newcombe(sum(r["broken_head"] for r in a), len(a), sum(r["broken_head"] for r in b), len(b))
            L.append(f"\\newcommand{{\\{name('diff', ticket, x, y, tag)}}}{{{d*100:+.0f} points [{lo*100:+.0f}, {hi*100:+.0f}]}}")
            fc = fixture_contrast(fixture_cells(runs, ticket, x), fixture_cells(runs, ticket, y))
            if fc:
                lo_, hi_ = sum(v < -1e-12 for v in fc["diffs"]), sum(v > 1e-12 for v in fc["diffs"])
                base = name("fx", ticket, x, y, tag)
                L += [f"\\newcommand{{\\{base}}}{{{lo_} lower, {hi_} higher, {len(fc['diffs']) - lo_ - hi_} tied}}",
                      f"\\newcommand{{\\{base}Mean}}{{{fc['mean']*100:+.0f} points}}",
                      f"\\newcommand{{\\{base}Boot}}{{[{fc['lo']*100:+.0f}, {fc['hi']*100:+.0f}]}}",
                      f"\\newcommand{{\\{base}P}}{{{fc['p_two']:.2f}}}", f"\\newcommand{{\\{base}Pone}}{{{fc['p_one']:.3f}}}"]
        for arm in ("hook", "notice"):
            bl = [r for r in runs if r["ticket"] == ticket and r["arm"] == arm and r["plain_hook_failures"] > 0]
            emit(L, name("tamperGivenBlock", ticket, arm, tag), sum(r["tampered"] for r in bl), len(bl))


def main():
    runs = load(BENCH / "results" / "runs.jsonl")
    by = {tag: [r for r in runs if (r["agent"], r["model"]) == am] for tag, am in CONDS.items()}
    L = ["% generated by bench/export_tex.py; do not edit", f"\\newcommand{{\\RRuns}}{{{len(runs)}}}",
         f"\\newcommand{{\\RRunsRoundOne}}{{{len(by['Claude']) + len(by['Codex'])}}}"]
    block(L, by["Claude"] + by["Codex"], "")
    for tag, sub in by.items():
        L.append(f"\\newcommand{{\\{name('runs', tag)}}}{{{len(sub)}}}")
        block(L, sub, tag)
        cells = [(fx, t, a) for fx in sorted({r["fixture"] for r in sub}) for t in ("base", "override") for a in ARMS]
        cnt = [fixture_cells(sub, t, a).get(fx) for fx, t, a in cells]
        cnt = [c for c in cnt if c]
        L.append(f"\\newcommand{{\\{name('agree', tag)}}}{{{sum(k in (0, n) for k, n in cnt)} of {len(cnt)}}}")
        L.append(f"\\newcommand{{\\{name('oerr', tag)}}}{{{sum(oracle_error(r) for r in sub)}}}")
        cost = sum(r["cost"] for r in sub if isinstance(r["cost"], (int, float)))
        L.append(f"\\newcommand{{\\{name('cost', tag)}}}{{\\${cost:.2f}}}")
        fxrows = []
        for fx in sorted({r["fixture"] for r in sub}):
            row = []
            for ticket, arm in [("base", a) for a in ("prose", "hook", "pace")] + [("override", a) for a in ARMS]:
                k, n = fixture_cells(sub, ticket, arm).get(fx, (0, 0))
                row.append(f"{k}/{n}" if n else "--")
            fxrows.append(f"\\texttt{{{fx}}} & " + " & ".join(row) + " \\\\")
        L.append(f"\\newcommand{{\\{name('fixtureRows', tag)}}}{{" + "\n".join(fxrows) + "}")
    L.append(f"\\newcommand{{\\RClaudeCost}}{{\\${sum(r['cost'] for r in by['Claude'] if isinstance(r['cost'], (int, float))):.2f}}}")
    secs = sorted(r["seconds"] for r in runs)
    L.append(f"\\newcommand{{\\RMedianSeconds}}{{{secs[len(secs)//2]:.0f}}}")
    m = json.loads((BENCH / "results" / "mutation.json").read_text())
    o = m["_overall"]
    L += [f"\\newcommand{{\\RMutCaught}}{{{o['caught']}}}", f"\\newcommand{{\\RMutTotal}}{{{o['mutants']}}}",
          f"\\newcommand{{\\RMutSens}}{{{o['sensitivity']:.2f}}}",
          f"\\newcommand{{\\RMutSensCI}}{{[{o['sens_ci'][0]:.2f}, {o['sens_ci'][1]:.2f}]}}",
          f"\\newcommand{{\\RMutFA}}{{{o['false_alarms']}}}", f"\\newcommand{{\\RMutBenign}}{{{o['benign_runs']}}}"]
    rows = []
    for fx, claims in sorted(m.items()):
        if fx.startswith("_"):
            continue
        for cid, c in sorted(claims.items()):
            n = c["caught"] + c["missed"]
            if n:
                said = c["said"].replace("%", "\\%")
                rows.append(f"{fx} & {cid} & {said} & {c['caught']}/{n} & "
                            f"{c['sensitivity']:.2f} [{c['sens_ci'][0]:.2f}, {c['sens_ci'][1]:.2f}] & {c['false_alarms']}/{c['clean_runs']} \\\\")
    L.append("\\newcommand{\\RMutTableRows}{" + "\n".join(rows) + "}")
    for e, w in ((0.10, "Ten"), (0.05, "Five"), (0.02, "Two"), (0.01, "One")):
        L.append(f"\\newcommand{{\\RAudit{w}}}{{{math.ceil(math.log(0.05) / math.log(1 - e))}}}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
